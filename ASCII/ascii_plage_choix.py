def couleurs_disponibles() -> bool:
    """True si le terminal sait afficher les couleurs ANSI."""
    res = False
    if not os.environ.get("NO_COLOR") and sys.stdout.isatty():
        if os.name == "nt":
            os.system("")
        res = True
    return res


def fg(c: tuple) -> str:
    """Code ANSI pour la couleur du texte."""
    return f"\033[38;2;{c[0]};{c[1]};{c[2]}m"


def bg(c: tuple) -> str:
    """Code ANSI pour la couleur du fond."""
    return f"\033[48;2;{c[0]};{c[1]};{c[2]}m"


RESET = "\033[0m"


def construire_grille() -> list:
    """Construit la grille de 72 x 36 pixels avec fond de plage et objets."""
    hauteur = len(FOND)
    largeur = len(FOND[0])
    grille = []

    for y in range(hauteur):
        ligne = []
        ligne_fond = FOND[y]
        ligne_objets = OBJETS[y] if y < len(OBJETS) else ""

        for x in range(largeur):
            pixel = int(ligne_fond[x]) if x < len(ligne_fond) else 3
            if pixel == 3 and (x + y * 3) % 11 == 0:
                pixel = 4  # léger grain de sable

            c_obj = ligne_objets[x] if x < len(ligne_objets) else "."
            if c_obj != ".":
                pixel = int(c_obj)

            ligne.append(pixel)
        grille.append(ligne)

    return grille


def rendre_image(grille: list) -> list:
    """Convertit la grille de pixels en lignes ANSI avec '▀'."""
    largeur = len(grille[0])
    lignes = []
    for y in range(0, len(grille), 2):
        haut = grille[y]
        bas = grille[y + 1]
        ligne = ""
        for x in range(largeur):
            ligne += fg(PALETTE[haut[x]]) + bg(PALETTE[bas[x]]) + "▀"
        lignes.append(ligne + RESET)
    return lignes


