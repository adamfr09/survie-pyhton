def couleurs_disponibles() -> bool:
    """True si le terminal sait afficher les couleurs ANSI."""
    res = False
    if not os.environ.get("NO_COLOR") and sys.stdout.isatty():
        if os.name == "nt":
            os.system("")
        res = True
    return res


def fg(c: tuple) -> str:
    """Code ANSI pour la couleur du texte."""
    return f"\033[38;2;{c[0]};{c[1]};{c[2]}m"


def bg(c: tuple) -> str:
    """Code ANSI pour la couleur du fond."""
    return f"\033[48;2;{c[0]};{c[1]};{c[2]}m"


RESET = "\033[0m"


def construire_grille(phase: int) -> list:
    """
    Génère une grille de 72 x 44 avec :
    - la plage et le front de vague animé selon `phase`
    - deux palmiers asymétriques sur les côtés, penchés vers l'intérieur
    - l'épave posée sur le sable avec ses brèches
    """
    hauteur = len(SCENE)
    largeur = len(SCENE[0])
    grille = []

    avance = int(3.5 + 3.0 * ((phase % 12) / 11.0)) if (phase % 24) < 12 else int(
        3.5 + 3.0 * (1.0 - ((phase - 12) % 12) / 11.0)
    )

    for y in range(hauteur):
        ligne = []
        ligne_palmiers = PALMIERS[y] if y < len(PALMIERS) else ""
        ligne_epave = EPAVE[y] if y < len(EPAVE) else ""
        ligne_breches = BRECHES[y] if y < len(BRECHES) else ""

        for x in range(largeur):
            if y >= 33:
                ondulation = int(1.5 * ((x + phase * 2) % 5 == 0))
                ligne_vague = 42 - avance + ondulation
                if y > ligne_vague:
                    pixel = 4
                elif y == ligne_vague and (x + phase) % 2 == 0:
                    pixel = 4
                else:
                    pixel = 3 if (x + y * 2) % 7 != 0 else 2
            else:
                pixel = 0

            c_palm = ligne_palmiers[x] if x < len(ligne_palmiers) else "."
            c_boat = ligne_epave[x] if x < len(ligne_epave) else "."
            c_hole = ligne_breches[x] if x < len(ligne_breches) else "."

            if c_palm != ".":
                pixel = int(c_palm)

            if c_hole == "0":
                pixel = 0
            elif c_boat != ".":
                pixel = int(c_boat)

            ligne.append(pixel)
        grille.append(ligne)

    return grille


def rendre_image(grille: list) -> list:
    """Convertit la grille de pixels en lignes ANSI avec '▀'."""
    largeur = len(grille[0])
    lignes = []
    for y in range(0, len(grille), 2):
        haut = grille[y]
        bas = grille[y + 1]
        ligne = ""
        for x in range(largeur):
            ligne += fg(PALETTE[haut[x]]) + bg(PALETTE[bas[x]]) + "▀"
        lignes.append(ligne + RESET)
    return lignes


def ascii_epave(cycles: int = 36, delai: float = 0.09) -> None:
    """Affiche la scène animée du bateau échoué et des vagues."""
    if not couleurs_disponibles():
        print(VERSION_SIMPLE)
        return

    print()
    nb_lignes = len(SCENE) // 2
    for phase in range(cycles):
        lignes = rendre_image(construire_grille(phase))
        if phase > 0:
            print(f"\033[{nb_lignes}A", end="")
        print("\n".join(lignes))
        time.sleep(delai)
    print()


if __name__ == "__main__":
    ascii_epave()